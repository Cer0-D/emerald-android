#!/usr/bin/env bash
# Android changes to the bootstrapped upstream tree, kept as one patch.
#   upstream_edit.sh snap <path...>   remember a file before editing it
#   upstream_edit.sh diff             write patches/pokeemerald/0090-android-clang.patch
# Snapshots live in build/android-snap (paths relative to build/upstream).
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
TREE="$REPO/build/upstream"
SNAP="$REPO/build/android-snap"
PATCH="$REPO/patches/pokeemerald/0090-android-clang.patch"
cmd="$1"; shift
case "$cmd" in
snap)
    for p in "$@"; do
        [[ -e "$SNAP/$p" ]] && continue
        mkdir -p "$SNAP/$(dirname "$p")"
        cp "$TREE/$p" "$SNAP/$p"
    done ;;
diff)
    tmp="$(mktemp)"
    {
        echo "Android (NDK clang, armeabi-v7a) build fixes for the game tree."
        echo "Generated by android_port/tools/upstream_edit.sh; edit build/upstream, then regenerate."
        echo
        ( cd "$SNAP" && find . -type f | sort ) | while read -r f; do
            f="${f#./}"
            diff -u --label "a/$f" --label "b/$f" "$SNAP/$f" "$TREE/$f" || true
        done
    } > "$tmp"
    mv "$tmp" "$PATCH"
    echo "wrote $PATCH" ;;
esac
